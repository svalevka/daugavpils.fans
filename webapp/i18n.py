DEFAULT_LANG = "ru"


def lang_prefix(lang: str) -> str:
    return "" if lang == DEFAULT_LANG else f"{lang}/"


def home_url(lang: str, base_path: str = "") -> str:
    return f"{base_path}/{lang_prefix(lang)}"


def band_url(lang: str, band_slug: str, base_path: str = "") -> str:
    return f"{base_path}/{lang_prefix(lang)}bands/{band_slug}/"


def release_url(lang: str, band_slug: str, release_slug: str, base_path: str = "") -> str:
    return f"{base_path}/{lang_prefix(lang)}bands/{band_slug}/{release_slug}/"


def band_media_page_url(lang: str, band_slug: str, base_path: str = "") -> str:
    return f"{base_path}/{lang_prefix(lang)}bands/{band_slug}/media/"


def release_media_page_url(lang: str, band_slug: str, release_slug: str, base_path: str = "") -> str:
    return f"{base_path}/{lang_prefix(lang)}bands/{band_slug}/{release_slug}/media/"


def members_index_url(lang: str, base_path: str = "") -> str:
    return f"{base_path}/{lang_prefix(lang)}members/"


def member_url(lang: str, member_slug: str, base_path: str = "") -> str:
    return f"{base_path}/{lang_prefix(lang)}members/{member_slug}/"


def feed_url(lang: str, base_path: str = "") -> str:
    return f"{base_path}/{lang_prefix(lang)}feed.xml"


def support_url(lang: str, base_path: str = "") -> str:
    return f"{base_path}/{lang_prefix(lang)}support/"


